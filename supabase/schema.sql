create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null unique
    check (username ~ '^[A-Za-z0-9_]{1,16}$'),
  role text not null
    check (role in ('lider', 'miembro_honorable', 'miembro')),
  created_at timestamptz not null default now()
);

insert into public.users (username, role)
values ('wNeofor', 'lider')
on conflict (username) do nothing;

alter table public.users enable row level security;

-- The bot uses the server-only service_role key, which bypasses RLS.
-- Do not grant anon/authenticated roles broad access to this table.
revoke all on table public.users from anon, authenticated;

create table if not exists public.command_history (
  id bigint generated by default as identity primary key,
  username text not null
    check (username ~ '^[A-Za-z0-9_]{1,16}$'),
  role text not null
    check (role in ('lider', 'miembro_honorable', 'miembro')),
  command text not null
    check (char_length(command) between 1 and 256),
  x double precision,
  y double precision,
  z double precision,
  created_at timestamptz not null default now()
);

create index if not exists command_history_username_created_at_idx
  on public.command_history (username, created_at desc);

alter table public.command_history enable row level security;
revoke all on table public.command_history from anon, authenticated;
